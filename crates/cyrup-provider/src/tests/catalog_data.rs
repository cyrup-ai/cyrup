/// **PROV-060 — the manifest must describe a provenance the data actually has.**
///
/// Before the `b0c2a90e` regeneration `generatedAt`/`source` named `b0c2a90e` while the note itself
/// conceded that 31 of the 35 files came from `91585d9a` — a drift guard reporting a floor the data
/// did not sit on. That regeneration made one revision generate every file, with the manifest
/// recording provenance per provider so the claim was machine-checkable rather than prose — even
/// though, at the time, there was no split left to describe.
///
/// **XAI_1 gives the map a REAL split to check.** `xai` is now fetched LIVE from
/// `https://pi.dev/api/models/providers/xai` on every `gen-catalogs` run instead of extracted from
/// the `b0c2a90e` pin, so its `source` is a URL and its `fetchedAt`/`revision` are its own, not
/// `pi@b0c2a90e`. The carve-out below is that datum, checked rather than asserted away.
///
/// **DRIFT-009 makes the split five catalogs wide**, and generalising the carve-out is how it stays
/// checkable. A live entry is recognised by its `source` being that provider's own pi.dev endpoint —
/// derived from the catalog NAME, so a live catalog cannot pass by naming somebody else's URL, and a
/// pinned catalog cannot pass by naming a URL at all. The top-level `source` stays `pi@b0c2a90e`
/// deliberately: it is the floor for the 34 files `git show` still produces, and repointing it at a
/// live fetch is what pi issue #7016 warns discards every persisted overlay.
/// **PROV-089 gives it a second.** `openrouter-images` is read at its own pin, `pi@v0.87.1` —
/// `image-models.generated.ts` stayed a tracked data literal through that tag, so the `b0c2a90e`
/// floor that binds every `*.models.ts` never bound it.
#[test]
fn the_catalog_manifest_names_one_revision_per_provider() {
    let raw = include_str!("../providers/catalog_manifest.json");
    let manifest: serde_json::Value = serde_json::from_str(raw).expect("manifest parses");

    let source = manifest["source"].as_str().expect("source");
    assert_eq!(source, "pi@b0c2a90e");

    let per_provider = manifest["catalogs"]
        .as_object()
        .expect("PROV-060: the manifest carries a per-provider source map");
    assert_eq!(
        per_provider.len(),
        catalogs().len(),
        "every embedded catalog must name its source module"
    );
    // PROV-071 — the live-fetched catalogs are now EVERY provider catalog, so the list is stated
    // as its complement: `openrouter-images` is the only file still taken from the pinned
    // revision, because it is not a provider module (its rows are the `openrouter` sub-record of
    // `image-models.generated.ts`, still a data literal in git) and
    // `pi.dev/api/models/providers/openrouter-images` is a 404. PROV-060 built this map precisely
    // so a provenance split is a DATUM rather than a footnote; the split is now one file wide, and
    // it is still checked in both directions below.
    const PINNED: &[&str] = &["openrouter-images"];
    let mut seen_live: Vec<&str> = Vec::new();
    for (name, entry) in per_provider {
        if !PINNED.contains(&name.as_str()) {
            seen_live.push(name);
            assert_eq!(
                entry["source"].as_str(),
                Some(format!("https://pi.dev/api/models/providers/{name}").as_str()),
                "{name}'s source is its OWN live endpoint, not the pinned revision and not \
                 another provider's URL"
            );
            assert!(
                entry["fetchedAt"].is_string() || entry["fetchedAt"].is_null(),
                "{name}'s fetchedAt is its own live provenance (string) or null (never fetched)"
            );
        } else if name == "openrouter-images" {
            assert_eq!(
                entry["source"].as_str(),
                Some("pi@v0.87.1"),
                "PROV-089: the images catalog is read at its own pinned tag, not b0c2a90e"
            );
        } else {
            assert!(
                !entry["source"]
                    .as_str()
                    .is_some_and(|src| src.starts_with("http")),
                "{name} is declared PINNED but names a live URL — move it, or the split stops \
                 being machine-checkable"
            );
            assert_eq!(
                entry["source"].as_str(),
                Some(source),
                "{name} names a different revision from the manifest's own — that split is \
                 exactly what PROV-060 filed"
            );
        }
        assert!(
            entry["module"]
                .as_str()
                .is_some_and(|m| m.starts_with("packages/ai/src/")),
            "{name} must name the upstream module it was extracted from"
        );
    }
    seen_live.sort_unstable();
    assert_eq!(
        seen_live.len(),
        per_provider.len() - PINNED.len(),
        "every catalog but the pinned one must be live-fetched (PROV-071)"
    );
    assert_eq!(seen_live.len(), 38);
    for name in PINNED {
        assert!(
            per_provider.contains_key(*name),
            "{name} is declared PINNED but is not in the manifest at all"
        );
    }

    // The 13-day residue between b0c2a90e and the ported tag is unmeasurable, and the manifest —
    // not only the ledger — has to say so, because the manifest is what a future refresher reads.
    let note = manifest["note"].as_str().expect("note");
    assert!(
        note.contains("PROV-071") && note.contains("a9f6a3159"),
        "the manifest must record WHY the pinned path is dead for provider modules: {note}"
    );
    // And that the floor is still a committed artifact, not something fetched at build or run
    // time — the distinction PROV-071 had to decide and the one a future refresher will re-ask.
    assert!(
        note.contains("COMMITTED FLOOR, NOT A RUNTIME FETCH"),
        "the manifest must say the catalogs are committed, not fetched: {note}"
    );

    // Every source module is one the generator actually knows how to read.
    assert!(
        per_provider["openrouter-images"]["module"]
            .as_str()
            .is_some_and(|m| m.ends_with("image-models.generated.ts")),
        "PROV-065: the images catalog has no *.models.ts counterpart and must not claim one"
    );
}

/// **PROV-018's drift check.** `#[ignore]`d because it needs a pi worktree on disk, which CI may
/// not have; run it with `cargo test -p cyrup-provider -- --ignored gen_catalogs` or, equivalently
/// and without cargo nesting, `cargo run -p xtask -- gen-catalogs --check`.
///
/// It fails the moment a catalog is hand-edited or the pinned revision moves — which is the guard
/// PROV-061 had to be closed without, and the reason the embedded data drifted a week behind its
/// own declared provenance for nine sweeps.
#[test]
#[ignore = "needs a pi worktree; run explicitly or via `cargo run -p xtask -- gen-catalogs --check`"]
fn gen_catalogs_check_reports_no_drift_against_the_pinned_revision() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("workspace root");
    let out = std::process::Command::new(env!("CARGO"))
        .current_dir(root)
        .args([
            "run",
            "--quiet",
            "-p",
            "xtask",
            "--",
            "gen-catalogs",
            "--check",
        ])
        .output()
        .expect("cargo run -p xtask");
    assert!(
        out.status.success(),
        "the embedded catalogs no longer reproduce from the pinned pi revision:\n{}\n{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr),
    );
}
