//! Embedded model-catalog data correctness (PROV-004).
//!
//! # Provenance
//!
//! cyrup ships **35** catalogs under `src/providers/catalog/*.json`. Thirty of them are a
//! **byte-faithful snapshot of pi @ `5c1a2977`** ("fix(ai): update generated model catalogue", 2026-06-30):
//! diffing every catalog field-by-field against that revision comes out identical for 30 of the 30
//! files that have a `packages/ai/src/providers/*.models.ts` counterpart, modulo three deltas that
//! upstream itself later adopted.
//!
//! pi then refreshed the catalogs seventeen times between `5c1a2977` and `91585d9a`
//! (2026-07-10 16:34) — the revision matching cyrup's own HEAD baseline date. cyrup never picked
//! that window up, so the embedded data was stale against cyrup's *own* declared baseline. This is
//! **owed debt, not post-baseline drift**: every commit cited below landed before 2026-07-10.
//!
//! The commits in that window that moved data these tests pin:
//!
//! | pi commit | date | effect |
//! |---|---|---|
//! | `cc2db980` | 2026-07-08 | switched generation to models.dev per-provider catalogs — retired 10 EOL Claude models, raised Sonnet 4.5 to 1M context, fixed `mistral-medium-latest`, zeroed the Xiaomi token-plan (prepaid) rates |
//! | `46145bef` | 2026-07-09 | OpenRouter context windows now come from the *top serving provider* rather than the theoretical model max |
//! | `fbdd4638` | 2026-07-09 | added the `max` thinking rung (covered by `thinking_max.rs`, PROV-002/DRIFT-008) |
//! | `7df2a94e` | 2026-07-09 | GPT-5.6 (`luna`/`sol`/`terra`) metadata |
//! | `5b4bda30`, `ee24a9ec`, `72d77b53`, `1da1cdb2`, `844d175e` | 2026-07-08..09 | generated-catalog refreshes |
//!
//! # Why these tests exist
//!
//! Every catalog is `include_str!`-ed and parsed with `serde_json::from_str(..).unwrap_or_default()`
//! (e.g. `providers/anthropic.rs:30`). A malformed edit therefore yields an **empty** provider
//! catalog with no diagnostic whatsoever — the failure is completely silent, and the only symptom
//! is a provider that mysteriously offers no models. `every_embedded_catalog_parses_non_empty`
//! closes that hole for the whole set, and the value assertions below stop a *well-formed but
//! wrong* number from going unnoticed.
//!
//! # Provenance, current — the history above is history
//!
//! **None of the hand-snapshot story above describes the current files.** Every catalog under
//! `src/providers/catalog/`, and `catalog_manifest.json` with them, is GENERATED by
//! `cargo run -p xtask -- gen-catalogs`, and `gen-catalogs --check` fails if a file stops
//! reproducing (PROV-018/PROV-060).
//!
//! **Where they are generated FROM changed with PROV-071, and that is the thing to read.** They
//! were all taken from one pinned pi revision, `b0c2a90e` (2026-07-17), by `git show` plus
//! `xtask/src/tsdata.rs`. That worked because `b0c2a90e` is the direct PARENT of `a9f6a3159`,
//! where pi began gitignoring `providers/data/` and collapsing every `*.models.ts` to a two-line
//! re-export — and it is the LAST revision at which any of them is a data literal. Which means it
//! was never a pin anybody chose: it is the newest answer `git show` can give, and it has been the
//! floor for every provider since. Measured at `v0.87.1`, 41 of 41 modules are re-exports and
//! `providers/data` is absent from the tree.
//!
//! So 38 of the 39 files now come LIVE from `https://pi.dev/api/models/providers/<id>` — the same
//! endpoint `remote_catalog.rs` overlays at runtime — and each carries its own `fetchedAt` and
//! `revision` in `catalog_manifest.json`. `openrouter-images` is the one exception and the reason
//! is structural, not a leftover: it is not a provider module (its rows are the `openrouter`
//! sub-record of `image-models.generated.ts`, still a data literal in git) and there is no live
//! endpoint for it.
//!
//! **The 13-day residue the old header recorded is gone with the pin.** `b0c2a90e` being 13 days
//! older than the ported tag `v0.83.0` made every value assertion here "a claim about b0c2a90e plus
//! an unbounded delta". The live source has no such gap — it is what pi is serving — so an
//! assertion below is a claim about pi's current published catalog, dated by the manifest entry for
//! that provider. What it is NOT is a claim about a named tag: pi publishes catalog data outside
//! its git history, so `v0.87.1` cannot be diffed against these files. Where pi HARDCODES a value
//! in `ai/scripts/generate-models.ts` the script itself is in git and remains the better witness;
//! that is what `xtask`'s `CONVERGED` table checks on every generation run.
//!
//! **Scale of the one refresh that closed PROV-071**, so the numbers below are not mistaken for
//! small edits: 536 rows added, 204 retired and 845 field values changed, across 27 catalogs.
