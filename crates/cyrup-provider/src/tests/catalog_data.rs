/// PROV-038, roster half: the set of catalog file stems must equal the registered provider ids plus
/// the images providers. Adding a sixth catalog without registering its provider now FAILS, which
/// is the drift the old tautological `CATALOGS.len() == 30` claimed to detect and could not.
#[test]
fn the_catalog_file_set_matches_the_registered_providers() {
    let mut on_disk: Vec<String> = catalogs().into_iter().map(|(name, _)| name).collect();
    on_disk.sort();
    let mut expected: Vec<String> = all_providers()
        .iter()
        .map(|p| p.id().as_str().to_string())
        .chain(IMAGES_CATALOGS.iter().map(|s| (*s).to_string()))
        .collect();
    // Several providers share one catalog file or ship none of their own; only assert that every
    // FILE has an owner, and that every registered provider that ships a file is present.
    expected.sort();
    expected.dedup();
    for name in &on_disk {
        assert!(
            expected.contains(name),
            "catalog {name}.json has no registered provider and is not an images catalog — \
             register it in providers/all.rs or delete the file"
        );
    }
}

/// PROV-030's regression guard (PROV-038 asked for it here): every row's `api` must be an api the
/// registry can actually construct, otherwise the model resolves, lists in `/model`, and then dies
/// at `wire.rs` with `no API implementation for <api>`.
///
/// **There is no carve-out, and there must never be one again.** `google-vertex` was the single
/// dangling api this guard was written around; `api/google_vertex.rs` closed it (PROV-030) and the
/// `KNOWN_DANGLING` exemption list was deleted in the same change, as the guard's own instructions
/// required. A fresh dangling api on any provider now fails here immediately — which is exactly what
/// would have stopped PROV-030 shipping.
#[test]
fn every_catalog_row_names_a_registered_api() {
    let registry = crate::api::builtin_registry();
    for (name, blob) in catalogs() {
        if IMAGES_CATALOGS.contains(&name.as_str()) {
            continue; // resolved through the images registry, not the text one
        }
        let models: Vec<Model> = serde_json::from_str(&blob).unwrap_or_default();
        for m in &models {
            assert!(
                registry.contains(&m.api),
                "{name}: {} names api `{}`, which register_builtins() does not provide — \
                 every request on this row would die with `no API implementation for {}`",
                m.id,
                m.api,
                m.api
            );
        }
    }
}

/// PROV-039: the manifest's own note counts the embedded catalogs, and its `generatedAt` is the
/// pi.dev overlay's staleness floor (`providers/all.rs:95` → `remote_catalog.rs:188-196`). Both
/// drifted from the file set; this pins them together so the next refresh cannot repeat it.
#[test]
fn the_catalog_manifest_matches_the_file_set() {
    let raw = include_str!("../providers/catalog_manifest.json");
    let manifest: serde_json::Value = serde_json::from_str(raw).expect("manifest parses");
    let note = manifest["note"].as_str().expect("note");
    let count = catalogs().len();
    assert!(
        note.contains(&format!("{count} embedded catalogs")),
        "the manifest note must state the real catalog count ({count}): {note}"
    );
    // The floor must be the LATEST extraction revision. b0c2a90e (2026-07-17T09:00:03Z) is the
    // newest any embedded catalog was taken from — see providers/google_vertex.rs's provenance
    // note — so an overlay dated between 2026-07-10 and that must be DISCARDED, not accepted.
    let generated_at =
        crate::providers::all::builtin_model_data_generated_at().expect("generatedAt parses");
    let jul_17 = 1_784_278_803_000_i64; // 2026-07-17T09:00:03Z
    assert_eq!(
        generated_at, jul_17,
        "the floor must be b0c2a90e's timestamp"
    );
}

/// Registered providers with NO embedded catalog, by design — each with the upstream fact that
/// makes it so. This list is asserted in BOTH directions below: an id here must really be empty,
/// and an empty provider must really be here, so an accidentally empty catalog still fails.
///
/// * `radius` — pi's only dynamic built-in, "purely dynamic providers (e.g. `radius`) that have
///   no static catalog entry" (`all.ts:50-52` @v0.84.4); the catalog comes from the gateway's
///   `/v1/config` (`providers/radius.rs`). PROV-014.
///
/// # DRIFT-009 emptied the rest of this list
///
/// `baseten` and the three `qwen-token-plan*` providers were here, on the reasoning that their rows
/// are models.dev data generated into a gitignored file and therefore obtainable from no revision.
/// The git half of that is still true at `v0.87.1`; the conclusion was not. `xtask`'s
/// `LIVE_CATALOGS` now fetches all four from `pi.dev/api/models/providers/<id>` — the same endpoint
/// the runtime overlay reads — so they ship 21, 20, 20 and 9 embedded rows and `radius` is the only
/// genuinely dynamic built-in left. `radius` is genuinely different in kind: its catalog is not a
/// published artifact at all, it is whatever the customer's own gateway answers at `/v1/config`,
/// so no amount of fetching upstream would produce a floor for it.
pub(crate) const DYNAMIC_ONLY_PROVIDERS: &[&str] = &["radius"];

/// The same guard one level up: every *registered* provider must expose a non-empty catalog —
/// except the [`DYNAMIC_ONLY_PROVIDERS`], which must expose an EMPTY one. Catches a loader wired
/// to the wrong file as well as a bad blob, and a dynamic member that quietly grew embedded rows
/// nobody sourced.
#[test]
fn every_registered_provider_has_a_non_empty_catalog() {
    let mut empty: Vec<String> = Vec::new();
    for p in all_providers() {
        let id = p.id().as_str().to_string();
        if DYNAMIC_ONLY_PROVIDERS.contains(&id.as_str()) {
            assert!(
                p.models().is_empty(),
                "provider {id} is listed as dynamic-only but ships {} embedded rows — either \
                 source them and remove it from DYNAMIC_ONLY_PROVIDERS, or delete the rows",
                p.models().len()
            );
            empty.push(id);
            continue;
        }
        assert!(
            !p.models().is_empty(),
            "provider {id} exposes zero models — catalog parse likely failed silently"
        );
    }
    empty.sort();
    let mut expected: Vec<String> = DYNAMIC_ONLY_PROVIDERS
        .iter()
        .map(|s| (*s).to_string())
        .collect();
    expected.sort();
    assert_eq!(
        empty, expected,
        "every dynamic-only provider must be registered, and nothing else may be empty"
    );
}

// -------------------------------------------------------------------------- the selection seam --

/// `Models::get_model` (collection.rs:108) is cyrup's port of pi `models.getModel` — the lookup
/// every consumer performs to turn a `provider/id` pair into the `Model` that shapes the request.
/// Asserting through it (rather than against the raw JSON) proves the corrected value actually
/// *reaches model selection*.
fn selection() -> Models {
    let mut models = create_models(CreateModelsOptions::default());
    for p in all_providers() {
        models.set_provider(p);
    }
    models
}

fn pick(models: &Models, provider: &str, id: &str) -> Model {
    models
        .get_model(provider, id)
        .unwrap_or_else(|| panic!("model selection could not find {provider}/{id}"))
}

// ------------------------------------------------------------------------------ the headline case --

/// **The headline PROV-004 case, reversed by PROV-149.** pi picked up a 1M-token context for
/// Sonnet 4.5 in `cc2db980` (`anthropic.models.ts:185-201` and `:202-218` @ `91585d9a` both read
/// `contextWindow: 1000000`), and PROV-004 raised cyrup's 200k to match. models.dev has since
/// moved both rows back to `contextWindow: 200000` with `inputLimits.images.maxPerRequest: 100`
/// (no upstream commit; pi.dev serves it, measured 2026-10-09). The window is what compaction and
/// overflow budgeting read, so a 1M floor lets a session budget past what the provider accepts.
/// `maxTokens` stays at 64000.
#[test]
fn sonnet_4_5_resolves_at_a_200k_window_and_100_images_per_request() {
    let models = selection();
    for id in ["claude-sonnet-4-5", "claude-sonnet-4-5-20250929"] {
        let m = pick(&models, "anthropic", id);
        assert_eq!(
            m.context_window, 200_000,
            "{id}: pi.dev serves contextWindow 200000 (PROV-149)"
        );
        assert_eq!(
            m.input_limits
                .as_ref()
                .and_then(|l| l.images.as_ref())
                .and_then(|i| i.max_per_request),
            Some(100),
            "{id}: pi.dev serves inputLimits.images.maxPerRequest 100 (PROV-149)"
        );
        assert_eq!(
            m.max_tokens, 64_000,
            "{id}: maxTokens is unchanged at 64000"
        );
    }
}

/// `claude-sonnet-4-6` doubled its output cap. pi `anthropic.models.ts:235` @ `91585d9a`:
/// `maxTokens: 128000`. cyrup capped generation at 64000, silently truncating long outputs.
#[test]
fn sonnet_4_6_max_tokens_is_128k() {
    let m = pick(&selection(), "anthropic", "claude-sonnet-4-6");
    assert_eq!(m.max_tokens, 128_000);
    assert_eq!(m.context_window, 1_000_000);
}

