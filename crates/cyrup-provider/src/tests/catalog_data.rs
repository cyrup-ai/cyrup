/// **PROV-059 — the field differences are behavioural, not cosmetic.**
///
/// `cost` feeds `/session` and every usage total; `maxTokens` and `contextWindow` feed overflow
/// estimation and the compaction trigger. Each assertion below is one of the ledger's named worst
/// cases, and each was RED before the regeneration.
#[test]
fn the_regenerated_field_values_match_the_pinned_revision() {
    let models = selection();

    // (a) every kimi-coding session reported ZERO spend: the rows were priced at 0/0/0/0. `k2p7`
    // and `kimi-k2-thinking` are retired; `kimi-for-coding` carries the same rates `k2p7` did and
    // `k3` is the flagship that replaced them, so both are priced here — the claim is that a
    // kimi-coding session bills something, and it needs a row that is actually shipped to make it.
    let kfc = pick(&models, "kimi-coding", "kimi-for-coding");
    assert_eq!(
        (kfc.cost.input, kfc.cost.output, kfc.cost.cache_read),
        (0.95, 4.0, 0.19)
    );
    let k3 = pick(&models, "kimi-coding", "k3");
    assert_eq!(
        (k3.cost.input, k3.cost.output, k3.cost.cache_read),
        (3.0, 15.0, 0.3)
    );

    // (b) cerebras billed cached reads at zero. `zai-glm-4.7` is retired; the two rows the
    // provider ships now BOTH price cache reads at zero, and that is upstream's own datum rather
    // than the defect this assertion was filed for — Cerebras does not charge for cached reads on
    // either. So the assertion moves to what is still checkable: the per-token rates are real.
    let cb = pick(&models, "cerebras", "qwen-3.8-27b");
    assert_eq!((cb.cost.input, cb.cost.output), (0.99, 1.49));

    // opencode's free tiers overstated their windows, deferring compaction past the real limit.
    assert_eq!(
        pick(&models, "opencode", "space-bunny-free").context_window,
        1_048_576
    );

    // openrouter carried 97 of the 129 differences; two representative ones, one per field class.
    assert_eq!(
        pick(&models, "openrouter", "anthropic/claude-sonnet-4").context_window,
        200_000,
        "the 1M window is the beta header's, not this row's"
    );
    assert_eq!(
        pick(&models, "openrouter", "openai/gpt-4o").cost.cache_read,
        1.25,
        "cached reads were billed at zero"
    );

    // vercel-ai-gateway's two Claude rows had maxTokens from a different model generation.
    assert_eq!(
        pick(&models, "vercel-ai-gateway", "anthropic/claude-opus-4").max_tokens,
        32_000
    );
}

