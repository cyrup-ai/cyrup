//! The built-in providers' classifier legs: pi's six `classifiers:` maps and the generated rows each
//! serves (PROV-147, PROV-153, PROV-155).
//!
//! Upstream, a provider that classifies is ONE `createProvider` call whose `models` array also
//! holds its `*_CLASSIFIER_MODELS` rows and whose `classifiers` map names an implementation per
//! api. At f1b2e77f5 exactly six providers carry such a map (`git grep 'classifiers:' --
//! packages/ai/src/providers`), and the generator writes classifier rows for exactly those six
//! (`scripts/generate-models.ts:3381-3392`):
//!
//! | provider | `classifiers` map | rows |
//! |---|---|---|
//! | `cloudflare-workers-ai` | `cloudflare-workers-ai.ts:21-23` | `CLOUDFLARE_WORKERS_AI_CLASSIFIER_MODELS`, `generate-models.ts:2649-2687` |
//! | `openai` | `openai.ts:31-33` | `OPENAI_CLASSIFIER_MODELS`, `:2696-2708` |
//! | `opencode` | `opencode.ts:25-26` | `OPENCODE_CLASSIFIER_MODELS`, `:2624-2647` |
//! | `openrouter` | `openrouter.ts:33-34` | decision models, `openrouter-catalog.ts:152-170` |
//! | `typesafe` | `typesafe.ts:14-16` | `loadModelsDevClassifierModels`, `:2586-2611` |
//! | `vercel-ai-gateway` | `vercel-ai-gateway.ts:15-16` | `type: "evaluation"` rows, `:1381-1396` |
//!
//! [`BUILTIN_CLASSIFIER_LEGS`] is that table. Each leg's rows are the embedded
//! `catalog/<id>-classifiers.json`, generated by `cargo run -p xtask -- gen-catalogs` from pi.dev
//! (never hand-written), and the file name is DERIVED from the leg's id, so a leg cannot load a
//! neighbour's rows. A provider with a map always has its rows here, so an offline or first-run
//! user lists the same classifier models pi's built-ins list; the live overlay adds to them.
//!
//! Module providers attach their leg through its constant (`OPENAI_CLASSIFIERS.attach(..)`), which
//! the compiler checks; the two table-built fleets attach theirs by id through
//! [`with_builtin_classifiers`], next to their OAuth and image hooks.

use std::sync::Arc;

use crate::classifier::{ClassifierApiRegistry, ClassifierModel, KnownClassifierApi};
use crate::wire::WireProvider;

/// The file-stem and manifest-key suffix of a provider's classifier catalog (`xtask`'s
/// `CLASSIFIER_CATALOG_SUFFIX`): `<id>-classifiers.json`.
pub const CLASSIFIER_CATALOG_SUFFIX: &str = "-classifiers";

/// One built-in provider's classifier leg: its pi `classifiers` map, as the apis it registers, and
/// the generated rows it serves.
#[derive(Debug)]
pub struct BuiltinClassifierLeg {
    /// The provider id (pi `createProvider({ id })`).
    pub provider: &'static str,
    /// The apis of the provider's `classifiers` map, in pi's key order. Every map at f1b2e77f5 has
    /// exactly one entry; the slice keeps the shape pi's `Record<api, impl>` has.
    pub apis: &'static [KnownClassifierApi],
    catalog_json: &'static str,
}

macro_rules! classifier_legs {
    ($($(#[$meta:meta])* $const:ident => ($id:literal, [$($api:ident),+ $(,)?])),* $(,)?) => {
        $(
            $(#[$meta])*
            pub const $const: BuiltinClassifierLeg = BuiltinClassifierLeg {
                provider: $id,
                apis: &[$(KnownClassifierApi::$api),+],
                // Derived from the id, so a leg cannot load a neighbour's file.
                catalog_json: include_str!(concat!("catalog/", $id, "-classifiers.json")),
            };
        )*
        /// Every built-in classifier leg: pi's six `classifiers` maps @f1b2e77f5, in provider-id
        /// order.
        pub const BUILTIN_CLASSIFIER_LEGS: &[BuiltinClassifierLeg] = &[$($const),*];
    };
}

classifier_legs! {
    /// `classifiers: { "cloudflare-workers-ai-system-one":
    /// cloudflareClassifier(cloudflareWorkersAISystemOneApi()) }` (`cloudflare-workers-ai.ts:21-23`).
    /// pi's `cloudflareClassifier` substitutes `{CLOUDFLARE_ACCOUNT_ID}` into the row's base URL from
    /// the resolved env (`cloudflare-stream.ts:31-36`); here the provider's auth `resolve` already
    /// returns the substituted base URL, which `Models::classify` applies before dispatch
    /// (`apply_classifier_auth`), so the api is registered bare. Rows: Clef, Clef Flash and Jev.
    CLOUDFLARE_WORKERS_AI_CLASSIFIERS => ("cloudflare-workers-ai", [CloudflareWorkersAiSystemOne]),
    /// `classifiers: { "openai-decisions": openAIDecisionsApi() }` (`openai.ts:31-33`): `gpt-6-luna`
    /// on OpenAI's Decisions API (PROV-147).
    OPENAI_CLASSIFIERS => ("openai", [OpenAiDecisions]),
    /// `classifiers: { "typesafe-system-one": typesafeSystemOneApi() }` (`opencode.ts:25-26`:
    /// "OpenCode Zen serves TypeSafe's System One protocol at /zen/v1/systemone"): `jev-1.13` and
    /// `jev-1.13-free`.
    OPENCODE_CLASSIFIERS => ("opencode", [TypesafeSystemOne]),
    /// `classifiers: { "typesafe-system-one": typesafeSystemOneApi() }` (`openrouter.ts:33-34`:
    /// "OpenRouter serves TypeSafe's System One protocol at /api/v1/systemone"): OpenRouter's
    /// decision models.
    OPENROUTER_CLASSIFIERS => ("openrouter", [TypesafeSystemOne]),
    /// `classifiers: { "typesafe-system-one": typesafeSystemOneApi() }` (`typesafe.ts:14-16`):
    /// `jev-latest`, TypeSafe's own endpoint (PROV-153).
    TYPESAFE_CLASSIFIERS => ("typesafe", [TypesafeSystemOne]),
    /// `classifiers: { "typesafe-system-one": typesafeSystemOneApi() }` (`vercel-ai-gateway.ts:15-16`:
    /// "AI Gateway serves TypeSafe's System One protocol at /typesafe/v1/systemone"): AI Gateway's
    /// evaluation models.
    VERCEL_AI_GATEWAY_CLASSIFIERS => ("vercel-ai-gateway", [TypesafeSystemOne]),
}

impl BuiltinClassifierLeg {
    /// The leg's generated rows (pi `getBuiltinClassifierModels(provider)`). A parse failure yields
    /// an empty list, surfaced by the catalog tests, rather than a panic (NO-PANIC policy).
    pub fn models(&self) -> Vec<ClassifierModel> {
        crate::catalog::load_classifier_catalog(self.catalog_json).unwrap_or_default()
    }

    /// The provider's `classifiers` dispatch map: each api with its built-in implementation.
    pub fn registry(&self) -> ClassifierApiRegistry {
        let mut registry = ClassifierApiRegistry::new();
        for api in self.apis {
            registry.register(*api, api.implementation());
        }
        registry
    }

    /// `provider` with this leg's rows and map attached.
    #[must_use]
    pub fn attach(&self, provider: WireProvider) -> WireProvider {
        provider
            .with_classifier_models(self.models())
            .with_classifiers(Arc::new(self.registry()))
    }
}

/// The classifier leg of the built-in provider `id`, if pi gives it a `classifiers` map.
pub fn builtin_classifier_leg(id: &str) -> Option<&'static BuiltinClassifierLeg> {
    BUILTIN_CLASSIFIER_LEGS
        .iter()
        .find(|leg| leg.provider == id)
}

/// Attach the built-in classifier leg to the provider `id`, if it has one — the per-id hook the
/// table-built fleets apply, shaped like [`super::builtin_oauth::builtin_provider_oauth`] and
/// [`super::openrouter::with_builtin_images`]. Every id without a leg is returned UNCHANGED, so it
/// cannot acquire `classify` by accident.
pub fn with_builtin_classifiers(id: &str, provider: WireProvider) -> WireProvider {
    match builtin_classifier_leg(id) {
        Some(leg) => leg.attach(provider),
        None => provider,
    }
}

/// Every generated classifier model of the built-in provider `id` (pi
/// `getBuiltinClassifierModels`, `providers/all.ts:120-129` @f1b2e77f5); empty for a provider with
/// none.
pub fn builtin_classifier_models(id: &str) -> Vec<ClassifierModel> {
    builtin_classifier_leg(id).map_or_else(Vec::new, BuiltinClassifierLeg::models)
}

/// One generated classifier model of the built-in provider `provider` (pi
/// `getBuiltinClassifierModel`, `providers/all.ts:82-92` @f1b2e77f5).
pub fn builtin_classifier_model(provider: &str, model_id: &str) -> Option<ClassifierModel> {
    builtin_classifier_models(provider)
        .into_iter()
        .find(|model| model.id.as_str() == model_id)
}

#[cfg(test)]
#[allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing
)]
mod tests {
    use super::*;
    use crate::classifier::AnyModel;
    use crate::provider::Provider;

    /// The legs are pi's six `classifiers` maps @f1b2e77f5, each with the api its map names (see
    /// the module table for every cite).
    #[test]
    fn the_legs_are_pis_six_classifier_maps() {
        let legs: Vec<(&str, Vec<&str>)> = BUILTIN_CLASSIFIER_LEGS
            .iter()
            .map(|leg| (leg.provider, leg.apis.iter().map(|a| a.as_str()).collect()))
            .collect();
        assert_eq!(
            legs,
            [
                (
                    "cloudflare-workers-ai",
                    vec!["cloudflare-workers-ai-system-one"]
                ),
                ("openai", vec!["openai-decisions"]),
                ("opencode", vec!["typesafe-system-one"]),
                ("openrouter", vec!["typesafe-system-one"]),
                ("typesafe", vec!["typesafe-system-one"]),
                ("vercel-ai-gateway", vec!["typesafe-system-one"]),
            ]
        );
    }

    /// Every leg serves rows, each tagged with the leg's provider and on an api its map dispatches.
    /// A row the map could not dispatch would answer "has no classifier implementation".
    #[test]
    fn every_leg_lists_only_its_own_rows_on_its_own_apis() {
        for leg in BUILTIN_CLASSIFIER_LEGS {
            let rows = leg.models();
            assert!(!rows.is_empty(), "{}: no classifier rows", leg.provider);
            let registry = leg.registry();
            for row in &rows {
                assert_eq!(row.provider.as_str(), leg.provider, "{}", row.id);
                assert!(
                    leg.apis.iter().any(|api| api.as_str() == row.api.as_str()),
                    "{}/{}: api {} is not in the leg's map",
                    leg.provider,
                    row.id,
                    row.api
                );
                assert!(registry.contains(row.api.as_str()), "{}", row.id);
            }
        }
    }

    /// pi.dev serves pi's own generated artifact; for the rows pi's generator hardcodes, that
    /// artifact must equal the literal in git (`generate-models.ts:2624-2647` and `:2649-2687`
    /// @f1b2e77f5), field for field. For the two listing-derived legs, the base URL every row gets
    /// from the generator: `AI_GATEWAY_TYPESAFE_BASE_URL` (`:225`) and OpenRouter's
    /// `https://openrouter.ai/api/v1` (`openrouter-catalog.ts:166`).
    #[test]
    fn the_generators_hardcoded_rows_arrive_verbatim() {
        let row = |provider: &str, id: &str| {
            builtin_classifier_model(provider, id)
                .unwrap_or_else(|| panic!("{provider}/{id} is embedded"))
        };
        let check = |m: &ClassifierModel,
                     name: &str,
                     base_url: &str,
                     cost_input: f64,
                     context_window: u64| {
            assert_eq!(m.name, name, "{}", m.id);
            assert_eq!(m.base_url, base_url, "{}", m.id);
            assert_eq!(m.input.len(), 1, "{}: text only", m.id);
            assert_eq!(m.cost.input, cost_input, "{}", m.id);
            assert_eq!(m.cost.output, 0.0, "{}", m.id);
            assert_eq!(m.cost.cache_read, 0.0, "{}", m.id);
            assert_eq!(m.cost.cache_write, 0.0, "{}", m.id);
            assert_eq!(m.context_window, context_window, "{}", m.id);
        };
        let opencode = builtin_classifier_models("opencode");
        assert_eq!(opencode.len(), 2);
        check(
            &row("opencode", "jev-1.13"),
            "Jev 1.13",
            "https://opencode.ai/zen/v1",
            0.042,
            32000,
        );
        check(
            &row("opencode", "jev-1.13-free"),
            "Jev 1.13 Free",
            "https://opencode.ai/zen/v1",
            0.0,
            32000,
        );

        // `CLOUDFLARE_WORKERS_AI_REST_BASE_URL` (`api/cloudflare.ts:6-7`), placeholder included.
        const WORKERS_AI: &str =
            "https://api.cloudflare.com/client/v4/accounts/{CLOUDFLARE_ACCOUNT_ID}/ai";
        assert_eq!(builtin_classifier_models("cloudflare-workers-ai").len(), 3);
        check(
            &row("cloudflare-workers-ai", "@cf/cloudflare/clef"),
            "Clef",
            WORKERS_AI,
            0.24,
            65536,
        );
        check(
            &row("cloudflare-workers-ai", "@cf/cloudflare/clef-flash"),
            "Clef Flash",
            WORKERS_AI,
            0.09,
            65536,
        );
        check(
            &row("cloudflare-workers-ai", "typesafe/jev"),
            "Jev",
            WORKERS_AI,
            0.0,
            32000,
        );

        for m in builtin_classifier_models("vercel-ai-gateway") {
            assert_eq!(
                m.base_url, "https://ai-gateway.vercel.sh/typesafe/v1",
                "{}",
                m.id
            );
        }
        for m in builtin_classifier_models("openrouter") {
            assert_eq!(m.base_url, "https://openrouter.ai/api/v1", "{}", m.id);
        }
    }

    /// pi `classifier-models.test.ts:115-129` @f1b2e77f5, "exposes Jev only through classifier
    /// catalog accessors": `getBuiltinClassifierModel("typesafe", "jev-latest")` is TypeSafe's Jev,
    /// `getBuiltinClassifierModels("typesafe")` is `[jev]`, and through the built-in registry it is
    /// a classifier model and not a chat model.
    #[test]
    fn the_builtin_accessors_expose_jev_only_as_a_classifier() {
        let jev = builtin_classifier_model("typesafe", "jev-latest").expect("typesafe Jev");
        assert_eq!(jev.api.as_str(), "typesafe-system-one");
        assert_eq!(jev.provider.as_str(), "typesafe");
        assert_eq!(jev.context_window, 64000);
        assert_eq!(builtin_classifier_models("typesafe"), vec![jev.clone()]);
        assert!(builtin_classifier_model("typesafe", "no-such-model").is_none());
        assert!(builtin_classifier_models("anthropic").is_empty());

        let provider = super::super::typesafe::typesafe_provider();
        assert!(
            provider.get_model("jev-latest").is_none(),
            "not a chat model"
        );
        let all: Vec<AnyModel> = provider.get_all_models();
        assert_eq!(all, vec![AnyModel::Classifier(jev)]);
    }

    /// Every built-in WITHOUT a leg is left alone by the hook: no classifier rows and no
    /// `classify`. Non-regression guard; red if the hook attached a leg on a miss.
    #[test]
    fn every_other_builtin_is_left_alone() {
        for provider in super::super::all::all_providers() {
            let id = provider.id().as_str();
            if builtin_classifier_leg(id).is_some() {
                continue;
            }
            assert!(!provider.supports_classification(), "{id}");
            assert!(
                provider
                    .get_all_models()
                    .iter()
                    .all(|m| !matches!(m, AnyModel::Classifier(_))),
                "{id}"
            );
        }
    }
}
